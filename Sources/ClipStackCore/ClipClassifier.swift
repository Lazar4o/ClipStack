import Foundation

public struct CaptureRules: Sendable {
    public var captureText: Bool
    public var captureImages: Bool
    public var maxTextBytes: Int
    public var maxRichBytes: Int
    public var maxImageBytes: Int
    public var ignoredBundleIDs: Set<String>

    /// Password managers and keychain apps: never record what they copy.
    public static let defaultIgnoredBundleIDs: Set<String> = [
        "com.apple.keychainaccess",
        "com.apple.Passwords",
        "com.1password.1password",
        "com.agilebits.onepassword7",
        "com.bitwarden.desktop",
    ]

    public init(
        captureText: Bool = true,
        captureImages: Bool = true,
        maxTextBytes: Int = 5_000_000,
        maxRichBytes: Int = 5_000_000,
        maxImageBytes: Int = 50_000_000,
        ignoredBundleIDs: Set<String> = CaptureRules.defaultIgnoredBundleIDs
    ) {
        self.captureText = captureText
        self.captureImages = captureImages
        self.maxTextBytes = maxTextBytes
        self.maxRichBytes = maxRichBytes
        self.maxImageBytes = maxImageBytes
        self.ignoredBundleIDs = ignoredBundleIDs
    }
}

/// Raw content pulled off the pasteboard, before hashing/normalizing.
public enum CapturedClip: Equatable {
    case text(plain: String, rtf: Data?, html: Data?)
    case image(data: Data, uti: String)
}

public enum ClipClassifier {
    /// nspasteboard.org markers used by password managers and tools for data that must not be recorded.
    public static let skipMarkerTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "de.petermaurer.TransientPasteboardType",
        "com.typeit4me.clipping",
        "Pasteboard generator type",
    ]

    /// In priority order.
    public static let imageTypes = [
        PasteboardTypes.png, PasteboardTypes.tiff, PasteboardTypes.jpeg, PasteboardTypes.heic,
    ]

    /// Applies the capture rules (see docs/PLAN.md "Capture rules"). Returns nil when nothing should be recorded.
    public static func classify(_ pb: PasteboardReading, sourceBundleID: String?, rules: CaptureRules) -> CapturedClip? {
        let types = Set(pb.availableTypes)
        // 1. Nothing there (e.g. a password manager just cleared the clipboard).
        guard !types.isEmpty else { return nil }
        // 2. Concealed / transient data.
        guard types.isDisjoint(with: skipMarkerTypes) else { return nil }
        // 3. Copied from an ignored app.
        if let sourceBundleID, rules.ignoredBundleIDs.contains(sourceBundleID) { return nil }
        // 4. Finder file copies (they also carry the file icon as TIFF, which must not become an "image").
        guard !types.contains(PasteboardTypes.fileURL) else { return nil }

        // 5. What is available?
        // NSPasteboard converts other string flavours (UTF-16, legacy) to plain text automatically.
        let plain = pb.readString(type: PasteboardTypes.plainText)
        let hasText = plain.map { !$0.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty } ?? false
        let imageType = imageTypes.first { types.contains($0) }

        // 6. Text wins, unless it is just a URL next to an image (e.g. Safari "Copy Image").
        if let imageType, !hasText || isSingleURL(plain ?? "") {
            guard rules.captureImages else { return nil }
            guard let data = pb.readData(type: imageType), !data.isEmpty, data.count <= rules.maxImageBytes else {
                return nil
            }
            return .image(data: data, uti: imageType)
        }

        guard hasText, let plain, rules.captureText else { return nil }
        // 7. Size caps.
        guard plain.utf8.count <= rules.maxTextBytes else { return nil }
        let rtf = pb.readData(type: PasteboardTypes.rtf).flatMap { $0.count <= rules.maxRichBytes && !$0.isEmpty ? $0 : nil }
        let html = pb.readData(type: PasteboardTypes.html).flatMap { $0.count <= rules.maxRichBytes && !$0.isEmpty ? $0 : nil }
        return .text(plain: plain, rtf: rtf, html: html)
    }

    /// True for a lone http(s)/file URL with no whitespace inside.
    public static func isSingleURL(_ string: String) -> Bool {
        let s = string.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !s.isEmpty, !s.contains(where: { $0.isWhitespace }) else { return false }
        let lower = s.lowercased()
        return lower.hasPrefix("http://") || lower.hasPrefix("https://") || lower.hasPrefix("file://")
    }
}
